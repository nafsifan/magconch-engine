package com.magconch.engine.api;

/**
 * 模块生命周期契约接口
 * <p>
 * 所有挂载至 Magconch Engine 的子系统模块均须实现此契约，
 * 由核心 ModuleManager 统一进行生命周期管理调度。
 */
public interface EngineModule {

    // ==========================================
    // 基础元数据
    // ==========================================

    /**
     * 获取模块唯一英文标识符（小写下划线或短横线命名）
     *
     * @return 模块 ID
     */
    String getId();

    /**
     * 获取模块可读显示名称
     *
     * @return 模块显示名
     */
    String getName();

    // ==========================================
    // 生命周期回调
    // ==========================================

    /**
     * 模块加载并启用时的生命周期入口
     */
    void onEnable();

    /**
     * 模块卸载或停用时的清理与持久化入口
     */
    void onDisable();

    /**
     * 模块重载配置或运行时状态入口
     */
    void onReload();

    // ==========================================
    // 状态判定
    // ==========================================

    /**
     * 获取当前模块运行状态
     *
     * @return true 为正在运行，false 为已禁用
     */
    boolean isEnabled();

    /**
     * 设置当前模块运行状态标识
     *
     * @param enabled 是否启用
     */
    void setEnabled(boolean enabled);
}
